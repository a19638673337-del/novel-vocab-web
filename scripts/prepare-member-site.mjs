import {readdir,readFile,writeFile,mkdir,cp,rm} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const source=path.join(root,'client'),destination=path.join(root,'public');
const protectedNames=new Set(['app.mjs','library-data.mjs','story-data.mjs']);
const resources={};
const types={'.mjs':'text/javascript; charset=utf-8','.csv':'text/csv; charset=utf-8','.json':'application/json; charset=utf-8','.md':'text/markdown; charset=utf-8','.mp3':'audio/mpeg'};
// Only this generated output is cleared, never the authored client or source ledgers.
if(destination!==path.join(root,'public'))throw Error('Invalid output path');
await rm(destination,{recursive:true,force:true});await mkdir(destination,{recursive:true});
async function visit(dir,prefix=''){
 for(const entry of await readdir(dir,{withFileTypes:true})){
  const name=prefix+entry.name,full=path.join(dir,entry.name);
  if(entry.isDirectory()){await visit(full,name+'/');continue;}
  if(name==='index.html')continue;
  if(protectedNames.has(name)||name.startsWith('downloads/')||name.startsWith('assets/audio/')){
   let bytes=await readFile(full);
   if(name.startsWith('downloads/')&&name.endsWith('.csv')&&/(?:[A-Z]:[\\/])/i.test(bytes.toString('utf8')))throw Error('Member export contains a local source path: '+name);
   resources['/'+name]={type:types[path.extname(name)]||'application/octet-stream',body:bytes.toString('base64')};
  }else{const target=path.join(destination,name);await mkdir(path.dirname(target),{recursive:true});await cp(full,target);}
 }
}
await visit(source);
await mkdir(path.join(root,'server'),{recursive:true});
await writeFile(path.join(root,'server/generated-resources.mjs'),'// Generated by prepare-member-site.mjs; server-only.\nexport const resources='+JSON.stringify(resources)+';\n');
const html=await readFile(path.join(source,'index.html'),'utf8');
if(!html.includes('./app.mjs'))throw Error('Missing site entry');
const shell=html.replace(/\.\/app\.mjs(?:\?[^\"]*)?/, './bootstrap.mjs?v=zones1').replaceAll('v=prose1','v=zones1');
await writeFile(path.join(root,'server/generated-shell.mjs'),'export const shell='+JSON.stringify(shell)+';\n');
console.log(JSON.stringify({privateResources:Object.keys(resources).length,publicRoot:'public',sourceRoot:'client'}));
